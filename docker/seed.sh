#!/usr/bin/env bash
# Seeds the disposable Chatto test server from docker/compose.yml and writes
# .env.test for the live integration tests. Safe to re-run.
#
#   1. First-run setup via the public ServerSetupService/CompleteSetup RPC
#      (creates the owner account with a password).
#   2. Test channel + membership via the operator CLI inside the container.
#   3. Verifies password login.
#   4. Creates the bot accounts the live tests run as (docker/seed-bots.ts),
#      then writes .env.test.
#
# TEST-ONLY credentials. Override with CHATTO_TEST_LOGIN / CHATTO_TEST_PASSWORD /
# CHATTO_TEST_ROOM_NAME / CHATTO_TEST_PORT.
set -euo pipefail

DOCKER_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(dirname "$DOCKER_DIR")"
ENV_FILE="${CHATTO_TEST_ENV_FILE:-$REPO_DIR/.env.test}"

PORT="${CHATTO_TEST_PORT:-4000}"
BASE_URL="http://localhost:$PORT"
LOGIN="${CHATTO_TEST_LOGIN:-sdktest}"
PASSWORD="${CHATTO_TEST_PASSWORD:-chatto-ts-test-password}"
ROOM_NAME="${CHATTO_TEST_ROOM_NAME:-sdk-tests}"

compose() { docker compose -f "$DOCKER_DIR/compose.yml" "$@"; }
operator() { compose exec -T chatto /chatto operator -c /config/chatto.toml --json "$@"; }
die() { echo "seed: $*" >&2; exit 1; }

command -v jq >/dev/null || die "jq is required"
command -v bun >/dev/null || die "bun is required"

echo "seed: waiting for $BASE_URL/readyz"
for _ in $(seq 1 60); do
  curl -fsS -o /dev/null "$BASE_URL/readyz" 2>/dev/null && break
  sleep 1
done
curl -fsS -o /dev/null "$BASE_URL/readyz" || die "server not ready at $BASE_URL"

# 1. First-run setup. Returns failed_precondition once setup has completed.
setup_body="$(jq -nc --arg l "$LOGIN" --arg p "$PASSWORD" \
  '{serverName: "Chatto.ts Test", description: "Disposable server for SDK live tests", login: $l, displayName: "SDK Test", password: $p}')"
setup_resp="$(curl -sS -X POST "$BASE_URL/api/connect/chatto.auth.v1.ServerSetupService/CompleteSetup" \
  -H 'Content-Type: application/json' -H 'Connect-Protocol-Version: 1' -d "$setup_body")"
if [ "$setup_resp" = "{}" ]; then
  echo "seed: completed first-run setup, owner '$LOGIN' created"
elif [ "$(jq -r '.code // empty' <<<"$setup_resp")" = "failed_precondition" ]; then
  echo "seed: setup already completed, reusing owner '$LOGIN'"
else
  die "CompleteSetup failed: $setup_resp"
fi

# 2. Test channel + membership via the operator API (Unix socket in the container).
user_id="$(operator user get --login "$LOGIN" | jq -r '.member.user.id')"
[ -n "$user_id" ] && [ "$user_id" != "null" ] || die "user '$LOGIN' not found"

room_id="$(operator room list --name "$ROOM_NAME" | jq -r '.rooms[0].id // empty')"
if [ -z "$room_id" ]; then
  room_id="$(operator room create --name "$ROOM_NAME" --description "Chatto.ts live tests" | jq -r '.room.id')"
  echo "seed: created room #$ROOM_NAME ($room_id)"
else
  echo "seed: reusing room #$ROOM_NAME ($room_id)"
fi
operator room member add --room-id "$room_id" --user-id "$user_id" >/dev/null

# 3. Verify password login (fails here if the stored password differs).
login_body="$(jq -nc --arg l "$LOGIN" --arg p "$PASSWORD" '{login: $l, password: $p}')"
token="$(curl -sS -X POST "$BASE_URL/auth/login" -H 'Content-Type: application/json' -d "$login_body" | jq -r '.token // empty')"
[ -n "$token" ] || die "password login for '$LOGIN' failed"

# 4. Bot accounts with API keys, room membership and room permissions.
bot_env="$(CHATTO_BASE_URL="$BASE_URL" CHATTO_LOGIN="$LOGIN" CHATTO_PASSWORD="$PASSWORD" CHATTO_TEST_ROOM="$room_id" \
  bun "$DOCKER_DIR/seed-bots.ts")" || die "creating bot accounts failed"

cat >"$ENV_FILE" <<ENV
# Generated by docker/seed.sh for the local test server. TEST-ONLY values.
CHATTO_BASE_URL=$BASE_URL
CHATTO_LOGIN=$LOGIN
CHATTO_PASSWORD=$PASSWORD
CHATTO_TEST_ROOM=$room_id
$bot_env
ENV
echo "seed: wrote $ENV_FILE"
sed 's/\(_TOKEN=cht_BK_[^.]*\.\).*/\1<secret>/' "$ENV_FILE"
