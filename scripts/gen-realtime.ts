/**
 * Generates the realtime protobuf descriptor and TypeScript payload types from
 * a Chatto source checkout.
 *
 *   bun scripts/gen-realtime.ts [path/to/chatto/proto]   (default: ../Chatto/proto)
 *
 * Output:
 *   src/realtime/descriptor.json   - pruned protobufjs JSON descriptor
 *   src/realtime/generated.ts      - TS interfaces/unions for every reachable type
 */
import protobuf from 'protobufjs'
import { existsSync, writeFileSync } from 'fs'
import { join, resolve } from 'path'

const protoRoot = resolve(process.argv[2] ?? join(import.meta.dir, '../../Chatto/proto'))
const ENTRY = 'chatto/realtime/v1/realtime.proto'
const ROOTS = ['chatto.realtime.v1.RealtimeSubscribe', 'chatto.realtime.v1.RealtimeServerFrame']

// buf.validate options are irrelevant for decoding; stub the import so the
// parser does not need the protovalidate module.
const STUBS: Record<string, string> = {
  'buf/validate/validate.proto': 'syntax = "proto3"; package buf.validate;',
}

const root = new protobuf.Root()
root.resolvePath = (_origin, target) => {
  if (STUBS[target] != null) return target
  const local = join(protoRoot, target)
  if (existsSync(local)) return local
  return target // google/protobuf/* are bundled with protobufjs
}
// Feed stubs through the parser directly and mark them loaded.
for (const [name, src] of Object.entries(STUBS)) {
  protobuf.parse(src, root, { keepCase: false })
  ;(root as any).files.push(name)
}
root.loadSync(join(protoRoot, ENTRY), { keepCase: false, alternateCommentMode: true } as protobuf.IParseOptions)
root.resolveAll()

// ---- prune to reachable types -------------------------------------------
const keep = new Set<string>()
function visit(t: protobuf.ReflectionObject) {
  const name = t.fullName.slice(1)
  if (keep.has(name)) return
  keep.add(name)
  if (t instanceof protobuf.Type) {
    for (const f of t.fieldsArray) if (f.resolvedType) visit(f.resolvedType)
  }
}
for (const r of ROOTS) visit(root.lookup(r)!)

function prunedJSON(ns: protobuf.NamespaceBase): any {
  const out: Record<string, any> = {}
  for (const child of ns.nestedArray) {
    const name = child.fullName.slice(1)
    if (child instanceof protobuf.Type || child instanceof protobuf.Enum) {
      if (!keep.has(name)) continue
      const json: any = child.toJSON()
      delete json.options
      if (json.fields) for (const f of Object.values<any>(json.fields)) delete f.options
      if (child instanceof protobuf.Type && json.nested) {
        const nested = prunedJSON(child)
        if (Object.keys(nested).length) json.nested = nested
        else delete json.nested
      }
      delete json.comment
      out[child.name] = json
    } else if (child instanceof protobuf.Namespace) {
      const nested = prunedJSON(child)
      if (Object.keys(nested).length) out[child.name] = { nested }
    }
  }
  return out
}
const descriptor = { nested: prunedJSON(root) }
writeFileSync(join(import.meta.dir, '../src/realtime/descriptor.json'), JSON.stringify(descriptor) + '\n')

// ---- TypeScript types ------------------------------------------------------
const lines: string[] = [
  '// Code generated by scripts/gen-realtime.ts from the Chatto proto sources. DO NOT EDIT.',
  '/* eslint-disable */',
  '',
]
// Types keep their short proto names (a clash fails generation). Timestamps are
// rendered as ISO-8601 strings and Durations as milliseconds by the decoder.
function typeName(full: string): string {
  if (full === 'google.protobuf.Timestamp') return 'string'
  if (full === 'google.protobuf.Duration') return 'number'
  const short = full.split('.').pop()!
  return short
}
const SCALAR: Record<string, string> = {
  double: 'number', float: 'number', int32: 'number', uint32: 'number', sint32: 'number', fixed32: 'number', sfixed32: 'number',
  int64: 'number', uint64: 'number', sint64: 'number', fixed64: 'number', sfixed64: 'number',
  bool: 'boolean', string: 'string', bytes: 'Uint8Array',
}
const seenShort = new Map<string, string>()
for (const name of [...keep].sort()) {
  const t = root.lookup(name)!
  const short = name.split('.').pop()!
  if (seenShort.has(short) && seenShort.get(short) !== name) throw new Error(`type name clash: ${short} (${name} vs ${seenShort.get(short)})`)
  seenShort.set(short, name)
  if (name.startsWith('google.protobuf.')) continue
  const comment = (t as any).comment as string | null
  if (comment) lines.push('/** ' + comment.replace(/\*\//g, '* /').split('\n').join('\n * ') + ' */')
  if (t instanceof protobuf.Enum) {
    lines.push(`export type ${short} =\n` + Object.keys(t.values).map(v => `  | '${v}'`).join('\n') + '\n')
    continue
  }
  const type = t as protobuf.Type
  lines.push(`export interface ${short} {`)
  for (const f of type.fieldsArray) {
    let ts = f.resolvedType ? typeName(f.resolvedType.fullName.slice(1)) : SCALAR[f.type] ?? 'unknown'
    if (f.repeated) ts = `${ts}[]`
    if (f.map) ts = `Record<string, ${ts}>`
    if (f.comment) lines.push('  /** ' + f.comment.replace(/\*\//g, '* /').split('\n').join('\n   * ') + ' */')
    // The decoder fills scalar, enum, and repeated defaults. Message fields,
    // oneof members, and proto3 `optional` fields are absent when unset.
    const optional = !f.repeated && !f.map &&
      (f.resolvedType instanceof protobuf.Type || f.partOf != null || f.options?.proto3_optional === true)
    lines.push(`  ${f.name}${optional ? '?' : ''}: ${ts}`)
  }
  for (const o of type.oneofsArray) {
    if (o.name.startsWith('_')) continue
    lines.push(`  /** Name of the set \`${o.name}\` oneof member, if any. */`)
    lines.push(`  ${o.name}?: ${o.fieldsArray.map(f => `'${f.name}'`).join(' | ')}`)
  }
  lines.push('}', '')
}

// Map of event-case -> payload type, for typed event emitters.
const ev = root.lookupType('chatto.realtime.v1.RealtimeEvent')
const oneof = ev.oneofs['event']!
lines.push('/** Every realtime event variant, keyed by its camelCase oneof case name. */')
lines.push('export interface RealtimeEventPayloads {')
for (const f of oneof.fieldsArray) lines.push(`  ${f.name}: ${typeName(f.resolvedType!.fullName.slice(1))}`)
lines.push('}', '')
lines.push('export const REALTIME_EVENT_NAMES = [')
for (const f of oneof.fieldsArray) lines.push(`  '${f.name}',`)
lines.push('] as const satisfies readonly (keyof RealtimeEventPayloads)[]', '')
writeFileSync(join(import.meta.dir, '../src/realtime/generated.ts'), lines.join('\n'))
console.log(`kept ${keep.size} types from ${protoRoot}`)
