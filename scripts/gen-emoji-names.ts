/**
 * Generates src/util/emoji-names.gen.ts: Unicode emoji -> Chatto reaction name.
 *
 * Mirrors `emojiNameFromUnicode` in Chatto's packages/chatto-client
 * (messaging/emojiShortcodes.ts) so the SDK picks the same primary names as the
 * official client (e.g. thumbsup, not +1) and reactions aggregate together.
 *
 * Usage: bun scripts/gen-emoji-names.ts <chatto-repo-dir> <gemoji-module-dir>
 * (gemoji must be the version pinned by Chatto's apps/frontend, currently ^8.1.0;
 * install it anywhere with `bun add gemoji@8` and pass its node_modules/gemoji.)
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const [chattoDir, gemojiDir] = process.argv.slice(2)
if (!chattoDir || !gemojiDir) {
  console.error('usage: bun scripts/gen-emoji-names.ts <chatto-repo-dir> <gemoji-module-dir>')
  process.exit(1)
}
const messaging = resolve(chattoDir, 'packages/chatto-client/src/messaging')
const { gemoji } = await import(resolve(gemojiDir, 'index.js'))
const { emojiAdditions } = await import(resolve(messaging, 'emojiAdditions.gen.ts'))
const { emojiSkinTones } = await import(resolve(messaging, 'emojiSkinTones.gen.ts'))

type Entry = { emoji: string; names: string[] }
const names = new Map<string, string>()
const primary = new Set<string>()
for (const entry of [...gemoji, ...emojiAdditions] as Entry[]) {
  const name = entry.names[0] === '+1' || entry.names[0] === '-1' ? entry.names[1]! : entry.names[0]!
  names.set(entry.emoji, name)
  primary.add(name)
}
for (const [name, emoji] of Object.entries(emojiSkinTones as Record<string, string>)) {
  if (primary.has(name.split('::')[0]!)) names.set(emoji, name)
}

const body = [...names].map(([e, n]) => `  ${JSON.stringify(e)}: ${JSON.stringify(n)},`).join('\n')
const out = `// Generated by scripts/gen-emoji-names.ts. DO NOT EDIT.
/** Unicode emoji (including skin-tone sequences) -> Chatto reaction name. ${names.size} entries. */
export const EMOJI_NAMES: Readonly<Record<string, string>> = {
${body}
}
`
writeFileSync(resolve(import.meta.dir, '../src/util/emoji-names.gen.ts'), out)
console.log(`wrote ${names.size} entries`)
